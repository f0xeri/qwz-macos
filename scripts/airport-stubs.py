#!/usr/bin/env python3
"""Generate Unsupported overrides for unimplemented native Wi-Fi requests.

Usage: scripts/airport-stubs.py (also run by build.sh).
Signatures come from airport/abi/. Methods implemented in
QwzAirportInterface.hpp are excluded. Verify the headers with kc-abi.py --check.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ABI = os.path.join(ROOT, 'airport/abi/Airport/macOS26')
# base first: a later (more derived) declaration overrides an earlier one
CHAIN = ['IOSkywalkInterface.h', 'IOSkywalkNetworkInterface.h', 'IOSkywalkEthernetInterface.h',
         'IO80211SkywalkInterface.h', 'IO80211InfraInterface.h', 'IO80211InfraProtocol.h']
HAND = os.path.join(ROOT, 'airport/QwzAirportInterface.hpp')
OUT = os.path.join(ROOT, 'airport/QwzAirportStubs.inc')

DECL = re.compile(r'^\s*virtual\s+(.+?)\s*\b(\w+)\s*\(([^)]*)\)\s*(const)?\s*(=\s*0)?\s*;', re.M)
DEFAULT = {'IOReturn': 'kIOReturnUnsupported', 'SInt32': 'kIOReturnUnsupported'}


def main():
    pure = {}           # (name, args, const) -> return type, for still-pure methods
    for h in CHAIN:
        text = open(os.path.join(ABI, h)).read()
        for ret, name, args, const, is_pure in DECL.findall(text):
            key = (name, re.sub(r'\s+', ' ', args.strip()), const)
            if is_pure:
                pure[key] = ret.strip()
            else:
                pure.pop(key, None)
    hand = open(HAND).read().split('#include "QwzAirportStubs.inc"')[0]
    done = set(re.findall(r'\b(\w+)\s*\([^)]*\)\s*(?:const\s*)?override', hand))
    lines = ['/* Generated by scripts/airport-stubs.py from airport/abi; do not edit. */']
    n = 0
    for (name, args, const), ret in sorted(pure.items()):
        if name in done:
            continue
        if ret not in DEFAULT:
            sys.exit('airport-stubs.py: no default for %s %s(%s); implement it in %s'
                     % (ret, name, args, os.path.relpath(HAND, ROOT)))
        lines.append('%s %s(%s)%s override { return %s; }'
                     % (ret, name, args, ' const' if const else '', DEFAULT[ret]))
        n += 1
    new = '\n'.join(lines) + '\n'
    if not os.path.exists(OUT) or open(OUT).read() != new:
        open(OUT, 'w').write(new)
    print('airport-stubs.py: %d stubs, %d requests implemented by hand' % (n, len(done)))


if __name__ == '__main__':
    main()
